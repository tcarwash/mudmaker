const assert=require('node:assert/strict');
const {defaults,plan,apply}=require('../../web/terrain-edit.js');
const base={grassland:{name:'Grassland',description:'A quiet stretch of grassland.'},water:{name:'Water',description:'Water stretches out before you.'}};
const source=()=>({default_map_id:'a',maps:[{id:'a',width:2,tiles:[{biome:'grassland',name:'Grassland',description:base.grassland.description}, {biome:'grassland'}]},{id:'b',width:2,tiles:[{biome:'grassland'}]}],entities:[],npcs:[],economy:{vendors:[]}});
let world=source();
assert.deepEqual(plan(world,'a',0,'water',base).groups,[]);
apply(world,'a',0,'water',[],base);
assert.equal(world.maps[0].tiles[0].name,'Water');
assert.equal(world.maps[0].tiles[0].description,base.water.description);
world=source();world.biomes={water:{name:'Deep lake',description:'Cold waves.'}};
assert.deepEqual(defaults(world,'water',base),{name:'Deep lake',description:'Cold waves.'});
const at={map_id:'a',location:{x:0,y:0}};
Object.assign(world.maps[0].tiles[0],{name:'Camp',description:'Custom prose',resources:[{item:'Herbs',quantity:3}],station:'campfire',rest:true,exits:{east:{x:1,y:0}},buildable:false});
world.entities=[{entity_type:'room',id:'room',...at},{entity_type:'custom_entity',id:'chest',...at},{entity_type:'room',id:'remote',map_id:'b',location:{x:0,y:0}}];
world.npcs=[{id:'local',...at},{id:'remote-npc',map_id:'b',location:{x:0,y:0}}];
let snapshot=structuredClone(world);
const groups=plan(world,'a',0,'water',base).groups.map(([key])=>key);
assert.deepEqual(groups,['name','description','resources','services','exits','buildable','rooms','objects']);
apply(world,'a',0,'water',groups,base);
assert.equal(world.maps[0].tiles[0].name,'Camp');assert.equal(world.entities[0].biome,'water');
assert.deepEqual(world.maps[0].tiles[0].resources,snapshot.maps[0].tiles[0].resources);
world=structuredClone(snapshot);apply(world,'a',0,'water',['rooms','objects'],base);
assert.equal(world.entities[0].name,'Deep lake');assert.equal(world.entities[0].description,'Cold waves.');
for(const key of ['resources','station','rest','exits','buildable'])assert.ok(!Object.hasOwn(world.entities[0],key));
world=structuredClone(snapshot);apply(world,'a',0,'water',[],base);
assert.deepEqual(world.entities.map(e=>e.id),['remote']);assert.deepEqual(world.npcs.map(e=>e.id),['remote-npc']);
assert.equal(world.maps[0].tiles[0].name,'Deep lake');
assert.equal(snapshot.entities.length,3);
console.log('Terrain defaults, selective preservation, room overrides and map isolation passed');
